/** 총괄 시트에 넣을 기관 집계 — 최상위 항목 평균. */
function rollup(rows) {
  const tops = rows.filter((row) => !row[0].includes("."));
  const avg = (index) => Math.round(tops.reduce((sum, row) => sum + row[index], 0) / tops.length);
  return { planned: avg(5), progress: avg(6) };
}

function build(data, headers, label) {
  const book = XLSX.utils.book_new();

  // 총괄 시트 — 기관별 산정 결과가 이미 계산돼 있는 실제 구조를 따른다.
  const summary = [
    [`${label} 연구개발 WBS 총괄`],
    ["※ 기관별 산정 기준이 달라 총괄값은 각 기관이 제출한 집계치를 그대로 씁니다."],
    [],
    ["기관", "계획(%)", "실적(%)", "차이(%p)", "WBS 항목", "기관별 산정 기준"],
    ...Object.entries(data).map(([name, rows]) => {
      const { planned, progress } = rollup(rows);
      return [name, planned / 100, progress / 100, (progress - planned) / 100, rows.length, "계층 자동집계"];
    }),
  ];
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(summary), "총괄");

  // 기관별 시트
  for (const [name, rows] of Object.entries(data)) {
    const grid = [
      [`${label} 연구개발 WBS — ${name}`],
      ["※ 일정은 실제 추진일정에 맞게 조정"],
      headers,
      ...rows.map((row) => [row[0], row[1], row[2], row[3], row[4], row[5] / 100, row[6] / 100, row[7], row[8]]),
    ];
    XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(grid), name);
  }

  // 코드 매핑 시트
  const mapping = [
    ["WBS 코드 매핑표"],
    ["기관별 신규 계층형 WBS코드와 기존코드를 연결합니다."],
    ["기관", "신규 WBS코드", "기존 WBS코드"],
    ...codeMap,
  ];
  XLSX.utils.book_append_sheet(book, XLSX.utils.aoa_to_sheet(mapping), "코드 매핑");

  return XLSX.write(book, { type: "buffer", bookType: "xlsx" });
}

